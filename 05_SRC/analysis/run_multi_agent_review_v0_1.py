"""
run_multi_agent_review_v0_1.py  (05_SRC/analysis/)

AOSL Multi-Agent Review v0.1
-----------------------------
Five-agent pipeline that scores, critiques, repairs, re-scores, and
reports on a single AI output.

Agents
------
1. Scoring Agent   — AOSL constraint scoring on original output (score_row_real_judge)
2. Critic Agent    — Free-text structural critique via judge model
3. Repair Agent    — Revised output generated by the same judge model
4. Re-score Agent  — AOSL constraint scoring on repaired output
5. Report Agent    — Markdown + CSV report written to output folder

Usage
-----
Dry run (prints plan, no API calls):
    py 05_SRC\\analysis\\run_multi_agent_review_v0_1.py --dry-run

Live run with built-in demo input:
    py 05_SRC\\analysis\\run_multi_agent_review_v0_1.py

Options:
    --judge-model   OpenRouter model ID  (default: deepseek/deepseek-chat)
    --max-tokens    Max tokens per call  (default: 500)
    --timeout       Seconds per call     (default: 90)
    --prompt        Override demo prompt text
    --output        Override demo output text
    --dry-run       Print plan only, no API calls

Output folder: 06_OUTPUTS/multi_agent_review/v0_1/
"""

